"""Summarise `ppl conform` output into a Markdown score table.

    ./build/ppl conform tests/conformance/hpkit_cases.tsv > build/conform.txt
    python3 -I tools/conform_report.py build/conform.txt > tests/conformance/SCORE.md
"""
import collections, os, sys

here = os.path.dirname(os.path.abspath(__file__))
cases = os.path.join(here, '..', 'tests', 'conformance', 'hpkit_cases.tsv')
group = {}
for line in open(cases, encoding='utf-8'):
    if line.startswith('#'):
        continue
    f = line.rstrip('\n').split('\t')
    if len(f) >= 6:
        group[f[0]] = f[5]

rows = [l.rstrip('\n').split('\t') for l in open(sys.argv[1], encoding='utf-8') if l[:4] in ('PASS', 'FAIL')]
by_entry = collections.OrderedDict()
for r in rows:
    by_entry.setdefault(r[1], []).append(r[0] == 'PASS')
by_group = collections.defaultdict(lambda: [0, 0, 0, 0])   # rows pass, rows, names all-pass, names
for e, oks in by_entry.items():
    g = group.get(e, '?')
    by_group[g][0] += sum(oks); by_group[g][1] += len(oks)
    by_group[g][2] += all(oks); by_group[g][3] += 1

tp = sum(v[0] for v in by_group.values()); tr = sum(v[1] for v in by_group.values())
tn = sum(v[2] for v in by_group.values()); tt = sum(v[3] for v in by_group.values())
print('# Conformance score against hp-prime-kit\n')
print('Generated by `make conform`. A name passes when every one of its rows passes.\n')
print('| Group | Rows passing | Names passing |')
print('|---|---|---|')
for g in sorted(by_group, key=lambda g: -by_group[g][1]):
    v = by_group[g]
    print('| %s | %d / %d | %d / %d |' % (g, v[0], v[1], v[2], v[3]))
print('\n## Names\n')
for e, oks in by_entry.items():
    print('- %s %s: %d/%d' % ('PASS' if all(oks) else 'fail', e, sum(oks), len(oks)))
print('\n**Total: %d / %d rows (%.1f%%), %d / %d names fully passing.**' % (tp, tr, 100.0 * tp / max(tr, 1), tn, tt))
